"""Render docs/MODEL_CARD.md from data/processed/evaluation.json (so the docs never drift)."""

from __future__ import annotations

import json

from . import config

LEADS = ("Jul", "Aug", "Sep", "Oct", "Nov")
DOC = config.ROOT / "docs" / "MODEL_CARD.md"


def _f(v, digits=3):
    return "–" if v is None else f"{v:.{digits}f}"


def _pct(v):
    return "–" if v is None else f"{round(v * 100)}%"


def render(ev: dict) -> str:
    ch, data, proto = ev["chosen"], ev["data"], ev["protocol"]
    trend = next(c for c in ev["candidates"] if c["key"] == "trend|none|w=all")
    lines = [
        "# Model card - KrushiMitra AI",
        "",
        f"_Generated by `python -m pipeline report` on {ev['generated_at']}. Do not edit by hand._",
        "",
        "## Task",
        "",
        f"- **Target:** {ev['target']}.",
        f"- **Units of analysis:** {data['districts']} districts of Odisha, Kharif seasons "
        f"{data['first_season']}-{data['last_season_with_official_yield']} "
        f"({data['district_seasons']} district-seasons).",
        "- **Issue dates:** after the end of July, August, September, October and November of the season.",
        f"- **Weather through:** {data['weather_through']}.",
        "",
        "## Method",
        "",
        "Forecast = district trend x (1 + weather adjustment).",
        "",
        "- Trend: robust (Huber) linear fit per district on all earlier seasons.",
        "- Adjustment: rainfall vs the 1991-2020 normal (season and last two months), root-zone soil moisture, "
        "daytime temperature, longest dry spell, heavy-rain days, wettest 3-day spell, cyclone wind and "
        "distance-weighted exposure (IBTrACS), coastal and KBK flags - pooled across districts.",
        "- Candidates in the deployed pool: " + ", ".join(f"`{k}`" for k in ch["pool"]) + ".",
        f"- Deployment: {ch['description']}",
        f"- Uncertainty: {proto['intervals']}.",
        "",
        "## Evaluation protocol",
        "",
        f"- {proto['evaluation']}.",
        f"- Backtests start in {proto['first_backtest_season']}; validation seasons "
        f"{proto['validation_seasons'][0]}-{proto['validation_seasons'][-1]}, test seasons "
        f"{proto['test_seasons'][0]}-{proto['test_seasons'][-1]}.",
        f"- **Disclosure:** {proto['disclosure']}",
        "",
        "## Results - deployed system, test seasons",
        "",
        "Skill = 1 - MSE / MSE(trend only). Positive is better than the trend.",
        "",
        "| Issued after | District RMSE (t/ha) | District MAPE | District skill | State RMSE (t/ha) | State skill "
        "| 80% coverage | 90% coverage | Current model |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for lead in LEADS:
        s, st, cov = ch["test_by_lead"].get(lead), ch["state_test_by_lead"].get(lead), ch["coverage"].get(lead, {})
        cov80, cov90 = cov.get("80", {}).get("coverage"), cov.get("90", {}).get("coverage")
        lines.append(
            f"| end of {lead} | {_f(s and s['rmse'])} | {_f(s and s['mape'], 1)}% | {_f(s and s['skill_vs_trend'], 2)} "
            f"| {_f(st and st['rmse'])} | {_f(st and st['skill_vs_trend'], 2)} | {_pct(cov80)} | {_pct(cov90)} "
            f"| `{ch['current_choice'].get(lead, '-')}` |"
        )
    fixed = ch["fixed_split_protocol"]
    lines += [
        "",
        f"Reference points (mean over issue dates, test seasons): trend only {_f(trend['test_rmse_mean'])} t/ha; "
        f"last season's yield {_f(ev['baselines']['persistence']['test']['rmse'])}; mean of last five seasons "
        f"{_f(ev['baselines']['mean5']['test']['rmse'])}. The original fixed-split protocol would have deployed "
        f"`{fixed['would_have_chosen']}` (test RMSE {_f(fixed['test_rmse_mean'])}).",
        "",
        "## All candidates (mean RMSE over issue dates)",
        "",
        "| Candidate | Validation | Test | In pool |",
        "|---|---|---|---|",
    ]
    for c in sorted(ev["candidates"], key=lambda c: c["test_rmse_mean"]):
        lines.append(
            f"| `{c['key']}` | {_f(c['validation_rmse_mean'])} | {_f(c['test_rmse_mean'])} "
            f"| {'yes' if c.get('in_selection_pool') else 'no'} |"
        )
    flagged = data["flagged_rows"]
    lines += [
        "",
        "## Data quality",
        "",
        f"No official observation is removed. {len(flagged)} district-seasons are labelled as unusual relative to "
        "their own history and their five nearest districts (most are real shocks: the 1999 Super Cyclone, the "
        "2000/2002/2015 droughts, Cyclone Phailin in 2013, the 2017 brown planthopper outbreak). "
        "A sensitivity analysis without them is in `evaluation.json` (`sensitivity_excluding_flagged_rows`).",
        "",
        "## Limitations",
        "",
        "- Weather is sampled at one point per district from a ~50 km reanalysis grid (NASA POWER).",
        "- No irrigation, variety, sowing-date or input data; much of the year-to-year variation is unexplained.",
        "- Official district yields are estimates with reporting noise; intervals are therefore wide.",
        "- Yields are milled-rice equivalent (DES convention). Not farm-level or financial advice.",
        "- The online-selection protocol was adopted after seeing the first test results; seasons from 2025 on "
        "are the first fully independent evaluation.",
        "",
    ]
    return "\n".join(lines)


def write(ev: dict | None = None) -> None:
    if ev is None:
        ev = json.loads((config.PROCESSED / "evaluation.json").read_text(encoding="utf-8"))
    DOC.parent.mkdir(parents=True, exist_ok=True)
    DOC.write_text(render(ev), encoding="utf-8")
